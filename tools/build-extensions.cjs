const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const modules = [
  'metadata.js', 'manifest_reader.js', 'manifest_parsers.js', 'desktop_handoff.js',
  'youtube_resolver.js', 'page_resolver.js', 'runtime.js'
];

function backgroundBundle() {
  const header = '// Generated by node tools/build-extensions.cjs. Edit extensions/shared/background instead.\n';
  return header + modules.map(name =>
    `\n// Source: extensions/shared/background/${name}\n` +
    fs.readFileSync(path.join(root, 'extensions/shared/background', name), 'utf8')
  ).join('');
}

function build(check = false) {
  const bundle = backgroundBundle();
  for (const browser of ['chrome', 'firefox']) {
    const target = path.join(root, 'extensions', browser, 'background.js');
    if (check) {
      if (fs.readFileSync(target, 'utf8') !== bundle)
        throw new Error(`${browser}/background.js is stale. Run node tools/build-extensions.cjs.`);
    } else fs.writeFileSync(target, bundle);
  }
}

if (require.main === module) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node tools/build-extensions.cjs [--check]');
  build(process.argv.includes('--check'));
  console.log('Chrome and Firefox background bundles are synchronized.');
}

module.exports = { backgroundBundle, build, modules };
